/**
 * TV-facing type scale. Every body / title / headline / label size is at or
 * above 14sp (couch-distance floor). Only the smallest label slots
 * (labelSmall, bodySmall for dense chrome) dip to 12sp.
 *
 * All letterSpacing values are sp (TextUnit) — never Float — to keep line
 * rhythm consistent with font scaling and accessibility text-size settings.
 *
 * fontFamily = FontFamily.Default is the system sans (Roboto on Android TV,
 * SF Compact on Apple TV). The audit asks for a "real font, e.g. Netflix Sans
 * or Roboto or system"; the system sans is the safest TV default because it
